_lang = "fr"
_static = {}
_tmpl = []


def _build():
    global _static, _tmpl
    _static, _tmpl = {}, []
    for row in T:
        fr = row[0]
        if "{0}" in fr:
            parts = re.split(r"\{(\d)\}", fr)
            rx = ""
            for k, p in enumerate(parts):
                rx += f"(?P<g{p}>.*?)" if k % 2 else re.escape(p)
            lit = len(re.sub(r"\{\d\}", "", fr))
            _tmpl.append((lit, re.compile("^" + rx + "$", re.S), row))
        else:
            _static[fr] = row
    _tmpl.sort(key=lambda t: -t[0])


_build()


def set_lang(code):
    global _lang
    _lang = code if code in LANGS else "fr"


def get_lang():
    return _lang


def detect_lang():
    """Langue de Windows (ou de l'environnement) si elle est disponible, sinon anglais."""
    try:
        import ctypes
        import locale
        lid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        name = locale.windows_locale.get(lid, "")
    except Exception:
        import locale
        name = (locale.getlocale()[0] or "")
    code = name[:2].lower()
    return code if code in LANGS else "en"


def _one(s, depth=0):
    if _lang == "fr" or not s.strip():
        return s
    m = re.match(r"^(\s*)(.*?)(\s*)$", s, re.S)
    pre, core, post = m.group(1), m.group(2), m.group(3)
    row = _static.get(core)
    if row:
        return pre + row[ORDER.index(_lang)] + post
    if depth < 3:
        for _, rx, row in _tmpl:
            mm = rx.match(core)
            if mm:
                vals = {k[1:]: _one(v, depth + 1) for k, v in mm.groupdict().items()}
                out = row[ORDER.index(_lang)]
                for k, v in vals.items():
                    out = out.replace("{" + k + "}", v)
                return pre + out + post
    return s


def tr(s):
    """Traduit un texte de l'interface (texte entier, sinon ligne par ligne)."""
    if not isinstance(s, str) or _lang == "fr":
        return s
    out = _one(s)
    if out != s or "\n" not in s:
        return out
    return "\n".join(_one(line) for line in s.split("\n"))
